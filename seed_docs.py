def _existing() -> list[dict]:
    names = {b[0] for b in DEMO_BASES}
    return [b for b in rag.list_bases() if b["name"] in names]


def main() -> int:
    ap = argparse.ArgumentParser(description="写入「上传文档」的演示数据（三个库、九份文件）")
    ap.add_argument("--force", action="store_true", help="先删除已有演示库再重建")
    ap.add_argument("--dry-run", action="store_true", help="只打印，不写入")
    args = ap.parse_args()

    existing = _existing()
    total = sum(len(fn()) for _, _, fn in DEMO_BASES)
    print(f"[seed] 当前分类库 {len(rag.list_bases())} 个，其中演示库 {len(existing)} 个")
    print(f"[seed] 将要写入 {len(DEMO_BASES)} 个库、{total} 份文件：")
    for name, desc, fn in DEMO_BASES:
        docs = fn()
        print(f"       · {name}（{len(docs)} 份）：{desc}")
        for fn_name, _, data in docs:
            print(f"           - {fn_name}  {len(data) / 1024:.1f} KB")

    if existing and not args.force:
        print("[seed] 已有演示文档，跳过。要重建请加 --force。")
        return 0

    if args.dry_run:
        print("[seed] --dry-run，未写入。")
        return 0

    if existing:
        for b in existing:
            rag.delete_base(b["id"])
        print(f"[seed] 已删除 {len(existing)} 个旧演示库")

    if not rag.embedding_available():
        print("[seed] ! 向量模型不可用，将退回关键词索引（检索效果会差一些）")

    made_docs = 0
    for name, desc, fn in DEMO_BASES:
        base = rag.create_base(name, desc)
        for fn_name, ctype, data in fn():
            doc = rag.upload_document(base["id"], fn_name, data, content_type=ctype)
            print(
                f"[seed] + {base['name']} / {doc['name']}  "
                f"{doc['chars']} 字 · {doc['chunk_count']} 块 · "
                f"{'已向量化' if doc['embedded'] else '关键词索引'}"
            )
            made_docs += 1

    print(f"\n[seed] 完成：{len(DEMO_BASES)} 个库、{made_docs} 份文件")
    print("[seed] 接下来：python app/main.py 8090  →  顶栏「知识库」→ 切到「上传文档」")
    print("[seed] 试试搜「城中村」「结直肠癌筛查」「1-9月」—— 会同时命中台账/会议与这些文件")
    print("[seed] 清空：python seed_docs.py --force 前先删，或在界面上删这三个库")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
