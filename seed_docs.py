def _head(title: str, *, doc_no: str = "", org: str = "", date: str = "",
          index_no: str = "", url: str = "") -> str:
    """文件头的公文元数据。缺哪项就不写哪项，不占位。"""
    lines = [f"# {title}", ""]
    if doc_no:
        lines.append(f"文号：{doc_no}")
    if index_no:
        lines.append(f"索引号：{index_no}")
    if org:
        lines.append(f"发布机构：{org}")
    if date:
        lines.append(f"发布日期：{date}")
    if url:
        lines.append(f"原文链接：{url}")
    lines.append("")
    return "\n".join(lines)


