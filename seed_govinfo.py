def _url(path: str) -> str:
    if path.startswith("http"):
        return path
    return SITE + path


def render(topic: dict, prefix: str) -> str:
    """一份栏目的正文：元数据 + 条目清单 + 能回答什么 + 边界。"""
    lines = [
        f"# {topic['name']}（{prefix.rsplit(' › ', 1)[-1]}）",
        "",
        f"栏目入口：{topic['entry']}",
        f"栏目位置：{prefix} › {topic['name']}",
        f"责任单位：{topic['dept']}",
        f"条目采集：{FETCHED}，共 {len(topic['items'])} 条",
        "",
        "## 一、这个栏目装什么",
        "",
        topic["note"],
        "",
    ]
    # 入口说明和「栏目位置」重复时就不写第二遍 —— 十二个领域那张表里两者本来就
    # 是同一句话，印两行只会让文件看起来像模板没填完。
    note = str(topic.get("entry_note") or "").strip()
    if note and note != f"{prefix} › {topic['name']}":
        lines += [f"入口说明：{note}", ""]

    lines += [
        "## 二、近期公开信息",
        "",
        "| 发布日期 | 条目 | 类型 | 原文 |",
        "|---|---|---|---|",
    ]
    for date, title, path, kind in topic["items"]:
        lines.append(f"| {date} | {title} | {kind} | {_url(path)} |")

    lines += [
        "",
        "## 三、能回答的问题",
        "",
    ]
    for q in topic["ask"]:
        lines.append(f"- {q}")

    lines += [
        "",
        "## 四、检索词",
        "",
        topic["keywords"],
        "",
        "## 五、边界",
        "",
        "本文件只收录标题、发布日期和原文链接，没有转抄正文和附表 —— "
        "抽检公告的附表动辄几百行，抄进知识库只会把检索切碎。"
        "要具体数字（批次、金额、人数），点原文链接看附件。",
        "",
        "---",
        "",
        "来源：溧阳市人民政府门户网站（www.liyang.gov.cn）政府信息公开栏目，"
        f"采集日期 {FETCHED}。",
        "",
    ]
    return "\n".join(lines)


def build(entries: list[dict], prefix: str) -> list[tuple[str, str, bytes]]:
    out = []
    for t in entries:
        name = f"{t['name']}（{prefix.rsplit(' › ', 1)[-1]}栏目索引）.md"
        out.append((name, "text/markdown", render(t, prefix).encode("utf-8")))
    return out


def _existing() -> list[dict]:
    names = {b[0] for b in BASES}
    return [b for b in rag.list_bases() if b["name"] in names]


def main() -> int:
    ap = argparse.ArgumentParser(description="写入政务公开栏目索引（2 个库、21 份文件）")
    ap.add_argument("--force", action="store_true", help="先删除已有同名库再重建")
    ap.add_argument("--dry-run", action="store_true", help="只打印，不写入")
    args = ap.parse_args()

    existing = _existing()
    total = sum(len(b[2]) for b in BASES)
    print(f"[gov] 当前分类库 {len(rag.list_bases())} 个，其中同名库 {len(existing)} 个")
    print(f"[gov] 将要写入 {len(BASES)} 个库、{total} 份文件：")
    for name, desc, entries, _prefix, _kind in BASES:
        print(f"       · {name}（{len(entries)} 份）：{desc}")
        for t in entries:
            print(f"           - {t['name']}  {len(t['items'])} 条")

    if existing and not args.force:
        print("[gov] 已有同名库，跳过。要重建请加 --force。")
        return 0
    if args.dry_run:
        print("[gov] --dry-run，未写入。")
        return 0

    for b in existing:
        rag.delete_base(b["id"])
        print(f"[gov] 已删除旧库 {b['name']}")

    made = 0
    for name, desc, entries, prefix, kind in BASES:
        base = rag.create_base(name, desc, *(kind or ()))
        for fn_name, ctype, data in build(entries, prefix):
            doc = rag.upload_document(base["id"], fn_name, data, content_type=ctype)
            print(f"[gov] + {base['name']} / {doc['name']}  {doc['chars']} 字 · {doc['chunk_count']} 块")
            made += 1

    print(f"\n[gov] 完成：{len(BASES)} 个库、{made} 份文件")
    print("[gov] 试试搜「尊老金」「环评」「依申请公开」「安全生产事故」")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
