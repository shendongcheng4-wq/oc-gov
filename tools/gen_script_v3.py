def real_dur(src: str, fallback: float) -> float:
    """读源片实际时长；读不到就用设计时长。"""
    f = SRC / src
    if not f.exists():
        return fallback
    try:
        out = subprocess.run([FFPROBE, "-v", "error", "-show_entries", "format=duration",
                              "-of", "csv=p=0", str(f)],
                             capture_output=True, text=True, check=True).stdout.strip()
        return float(out)
    except Exception:
        return fallback

